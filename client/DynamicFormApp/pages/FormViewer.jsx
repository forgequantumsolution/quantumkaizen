const MinIOFileBrowserModal = ({
  open,
  onCancel,
  onSelectFile,
  isMultiple = false,
}) => {
  const [files, setFiles] = useState([]);
  const [loading, setLoading] = useState(false);
  const [selectedFiles, setSelectedFiles] = useState([]);
  const [subfolders, setSubfolders] = useState([]);
  const [currentFolder, setCurrentFolder] = useState(null);
  const [breadcrumb, setBreadcrumb] = useState([{ id: null, name: "Root" }]);

  useEffect(() => {
    if (open) {
      fetchMinIOFiles();
    }
  }, [open, currentFolder]);

  const fetchMinIOFiles = async () => {
    try {
      setLoading(true);

      const res = await Axios.get(`${api}/dms/folders/my/`, {
        params: { folder_id: currentFolder },
        headers: {
          Authorization: `Bearer ${localStorage.getItem("Token")}`,
        },
      });

      if (res.data.status === "success") {
        setFiles(res.data.items || res.data.files || []);
        setSubfolders(res.data.subfolders || []);
      }
    } catch (error) {
      console.error("Error fetching MinIO files:", error);
      Toast.error("Failed to fetch files from storage");
    } finally {
      setLoading(false);
    }
  };

  const handleFolderClick = (folder) => {
    setCurrentFolder(folder.id);
    // setBreadcrumb([...breadcrumb, { id: folder.id, name: folder.name }]);
    setSelectedFiles([]);
  };

  const handleBreadcrumbClick = (index) => {
    const clickedFolder = breadcrumb[index];
    setCurrentFolder(clickedFolder.id);
    setBreadcrumb(breadcrumb.slice(0, index + 1));
    setSelectedFiles([]);
  };

  const handleFileSelect = (file) => {
    if (isMultiple) {
      setSelectedFiles((prev) => {
        const exists = prev.find((f) => f.id === file.id);
        if (exists) {
          return prev.filter((f) => f.id !== file.id);
        }
        return [...prev, file];
      });
    } else {
      setSelectedFiles([file]);
    }
  };

  const handleConfirm = () => {
    if (selectedFiles.length === 0) {
      Toast.warning("Please select at least one file");
      return;
    }
    onSelectFile(isMultiple ? selectedFiles : selectedFiles[0]);
    setSelectedFiles([]);
  };

  const handleCancel = () => {
    onCancel();
    setSelectedFiles([]);
    setCurrentFolder(null);
    setBreadcrumb([{ id: null, name: "Root" }]);
  };

  return (
    <Modal
      open={open}
      onCancel={handleCancel}
      title="Select Files from Storage"
      width={800}
      destroyOnHidden
      footer={[
        <Button
          key="cancel"
          onClick={handleCancel}
          data-testid="form-viewer-minio-btn-cancel"
        >
          Cancel
        </Button>,
        <Button
          key="confirm"
          type="primary"
          onClick={handleConfirm}
          disabled={selectedFiles.length === 0}
          data-testid="form-viewer-minio-btn-select"
        >
          Select {selectedFiles.length > 0 && `(${selectedFiles.length})`}
        </Button>,
      ]}
    >
      <div className="space-y-4">
        <div
          style={{
            padding: "8px 12px",
            backgroundColor: "#f5f5f5",
            borderRadius: "4px",
            display: "flex",
            alignItems: "center",
            gap: "8px",
          }}
        >
          {/* {breadcrumb.map((item, index) => (
            <React.Fragment key={item.id || 'root'}>
              <span
                onClick={() => handleBreadcrumbClick(index)}
                style={{
                  cursor: 'pointer',
                  color: index === breadcrumb.length - 1 ? '#000' : '#1890ff',
                  fontWeight: index === breadcrumb.length - 1 ? 'bold' : 'normal',
                }}
              >
                {item.name}
              </span>
              {index < breadcrumb.length - 1 && <span>/</span>}
            </React.Fragment>
          ))} */}
        </div>
        <div
          style={{
            maxHeight: "400px",
            overflowY: "auto",
            border: "1px solid #f0f0f0",
            borderRadius: "8px",
            padding: "8px",
          }}
        >
          {loading ? (
            <div className="text-center py-8">Loading...</div>
          ) : (
            <>
              {subfolders.length > 0 && (
                <Space
                  direction="vertical"
                  style={{ width: "100%", marginBottom: "16px" }}
                >
                  {subfolders.map((folder) => (
                    <Card
                      key={folder.id}
                      hoverable
                      onClick={() => handleFolderClick(folder)}
                      style={{
                        cursor: "pointer",
                        backgroundColor: "#fafafa",
                        border: "1px solid #d9d9d9",
                      }}
                    >
                      <div className="flex items-center gap-3">
                        <NxFolder
                          style={{ fontSize: "24px", color: "#faad14" }}
                        />
                        <div>
                          <div className="font-semibold">{folder.name}</div>
                          <div className="text-sm text-gray-500 dark:text-gray-400">
                            Folder
                          </div>
                        </div>
                      </div>
                    </Card>
                  ))}
                </Space>
              )}

              {files.length === 0 && subfolders.length === 0 ? (
                <div className="text-center py-8 text-gray-400">
                  No files or folders found
                </div>
              ) : files.length > 0 ? (
                <Space direction="vertical" style={{ width: "100%" }}>
                  {files.map((file) => {
                    const isSelected = selectedFiles.some(
                      (f) => f.id === file.id,
                    );

                    return (
                      <Card
                        key={file.id}
                        hoverable
                        onClick={() => handleFileSelect(file)}
                        style={{
                          cursor: "pointer",
                          backgroundColor: isSelected ? "#e6f7ff" : "white",
                          border: isSelected
                            ? "2px solid #1890ff"
                            : "1px solid #d9d9d9",
                        }}
                      >
                        <div className="flex items-center justify-between">
                          <div className="flex items-center gap-3">
                            {isMultiple && <Checkbox checked={isSelected} />}
                            {file.file_type?.startsWith("image/") &&
                              file.url && (
                                <img
                                  src={file.url}
                                  alt={file.name}
                                  style={{
                                    width: "40px",
                                    height: "40px",
                                    objectFit: "cover",
                                    borderRadius: "4px",
                                  }}
                                />
                              )}

                            <div>
                              <div className="font-semibold">{file.name}</div>
                              <div className="text-sm text-gray-500 dark:text-gray-400">
                                {formatFileSize(file.size)}
                              </div>
                            </div>
                          </div>
                          <Button
                            size="small"
                            onClick={(e) => {
                              e.stopPropagation();
                              window.open(file.url, "_blank");
                            }}
                            disabled={!file.url}
                          >
                            Preview
                          </Button>
                        </div>
                      </Card>
                    );
                  })}
                </Space>
              ) : null}
            </>
          )}
        </div>
        {selectedFiles.length > 0 && (
          <Alert
            message={`${selectedFiles.length} file(s) selected`}
            type="info"
            showIcon
          />
        )}
      </div>
    </Modal>
  );
};

