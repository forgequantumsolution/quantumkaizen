// Helper component to sync dynamic select values when options are loaded
// This converts label values to full option objects { label, value } for dynamic select fields
const DynamicOptionsSyncEffect = ({ formik, dynamicOptions, formSchema }) => {
  useEffect(() => {
    if (!formSchema?.sections || Object.keys(dynamicOptions).length === 0)
      return;

    const allFields = formSchema.sections.flatMap(
      (section) => section.fields || [],
    );
    const dynamicFields = allFields.filter(
      (field) => field.dynamic && field.type === "select",
    );

    dynamicFields.forEach((field) => {
      const options = dynamicOptions[field.name];
      if (!options || options.length === 0) return;

      const currentValue = formik.values[field.name];
      if (!currentValue) return;

      // Check if currentValue is already an object with label and value
      if (
        typeof currentValue === "object" &&
        currentValue.label &&
        currentValue.value
      ) {
        return; // Already in correct format
      }

      // Try to find option by label or ID match (if currentValue is a string)
      let matchingOption = null;
      if (typeof currentValue === "string") {
        // First check if it's an ID
        matchingOption = options.find((opt) => opt.value === currentValue);
        // If not found by ID, try by label
        if (!matchingOption) {
          matchingOption = options.find(
            (opt) =>
              opt.label === currentValue ||
              opt.label?.toLowerCase() === currentValue?.toLowerCase(),
          );
        }
      }

      if (matchingOption) {
        // Set the full option object { label, value } as expected by validation
        formik.setFieldValue(field.name, {
          label: matchingOption.label,
          value: matchingOption.value,
        });
      }
    });
  }, [dynamicOptions, formSchema, formik]);

  return null; // This component doesn't render anything
};

// Auto-trigger fetchAutoGeneratedValue when a dependent field changes
const AutoGenerateTriggerEffect = ({
  formik,
  formSchema,
  fetchAutoGeneratedValue,
}) => {
  const prevDepsRef = useRef({});

  useEffect(() => {
    if (!formSchema?.sections) return;

    const allFields = formSchema.sections.flatMap(
      (section) => section.fields || [],
    );
    const autoGenFields = allFields.filter(
      (f) =>
        f.auto_generate &&
        f.auto_generate_endpoint &&
        f.auto_generate_mappings &&
        Object.keys(f.auto_generate_mappings).length > 0,
    );

    autoGenFields.forEach((field) => {
      const mappedFieldNames = Object.values(
        field.auto_generate_mappings,
      ).filter(Boolean);
      if (mappedFieldNames.length === 0) return;

      // Build a combined key from all dependent field values
      const depValues = mappedFieldNames.map((name) => {
        const val = formik.values[name];
        return val?.value || val || "";
      });

      // All dependent fields must have values before triggering
      if (depValues.some((v) => !v)) return;

      const currentKey = depValues.join("|");
      const prevKey = prevDepsRef.current[field.name];

      // Only trigger if any dependent value actually changed
      if (currentKey !== prevKey) {
        prevDepsRef.current[field.name] = currentKey;

        // Skip re-generation if field already has a pre-filled value from backend
        // (e.g., returned ticket, revision ticket — document number already assigned)
        // Only generate when field is empty (first time creation)
        const existingValue = formik.values[field.name];
        if (existingValue && prevKey === undefined) {
          // First render with pre-filled value — don't overwrite, just track deps
          return;
        }

        fetchAutoGeneratedValue(field, formik);
      }
    });
  }, [formik.values, formSchema, fetchAutoGeneratedValue]);

  return null;
};

// Helper function to check if a value is empty (undefined, null, empty string, or empty array)
const isEmptyValue = (value) => {
  if (value === undefined || value === null || value === "") {
    return true;
  }
  if (Array.isArray(value) && value.length === 0) {
    return true;
  }
  return false;
};

// Helper function to get field value from form values or submission data
const getFieldValueForDependency = (
  targetField,
  targetFieldId,
  formValues,
  allSections,
) => {
  // First check form values - skip if empty
  let value = formValues[targetField];
  if (!isEmptyValue(value)) {
    return value;
  }

  // If not found in form values or empty, check submission data from all sections
  for (const section of allSections) {
    if (section.submission && Array.isArray(section.submission)) {
      for (const submission of section.submission) {
        if (submission.field_values && Array.isArray(submission.field_values)) {
          // Find by field name or field_id
          const fieldValue = submission.field_values.find(
            (fv) => fv.label === targetField || fv.field_id === targetFieldId,
          );
          if (
            fieldValue &&
            fieldValue.value !== undefined &&
            fieldValue.value !== null
          ) {
            return fieldValue.value;
          }
        }
      }
    }
  }

  return null;
};

// Helper function to check if a field should be visible based on its dependency
const isFieldVisible = (field, allSections, formValues) => {
  // If no dependency is configured, field is always visible
  if (!field.dependency) {
    return true;
  }

  // Support both cascader format and individual fields format
  const {
    field_section,
    field_name,
    option_selected,
    options_selected,
    cascader_selection,
    multiple_field_dependencies,
  } = field.dependency;

  // Extract dependency info
  let fieldDependencies = [];

  if (multiple_field_dependencies && multiple_field_dependencies.length > 0) {
    // Use multiple field dependencies directly
    fieldDependencies = multiple_field_dependencies;
  } else if (cascader_selection && cascader_selection.length > 0) {
    // Extract from cascader_selection format: [[section, field, option1], [section, field, option2], ...]
    const pathsByField = {};
    cascader_selection.forEach((path) => {
      if (path.length >= 3) {
        const [section, fieldName, option] = path;
        const key = `${section}|${fieldName}`;
        if (!pathsByField[key]) {
          pathsByField[key] = {
            field_section: section,
            field_name: fieldName,
            options_selected: [],
          };
        }
        pathsByField[key].options_selected.push(option);
      }
    });

    fieldDependencies = Object.values(pathsByField);
  } else if (field_section && field_name) {
    // Use individual fields (single dependency)
    const targetOptions =
      options_selected && options_selected.length > 0
        ? options_selected
        : option_selected
          ? [option_selected]
          : [];

    if (targetOptions.length > 0) {
      fieldDependencies = [
        {
          field_section,
          field_name,
          options_selected: targetOptions,
        },
      ];
    }
  }

  // If no valid dependency configuration, show field
  if (fieldDependencies.length === 0) {
    return true;
  }

  // Check if ANY of the target options match the current value for a single field
  const checkFieldDependency = (dependency) => {
    const {
      field_section: targetSection,
      field_name: targetField,
      options_selected: targetOptions,
    } = dependency;

    // Find the section that contains the dependency field
    const dependencySection = allSections.find(
      (section) => section.section_name === targetSection,
    );

    if (!dependencySection) {
      return true; // If dependency section not found, consider condition met
    }

    // Find the dependency field
    const dependencyField = dependencySection.fields.find(
      (f) => f.name === targetField,
    );

    if (!dependencyField) {
      return true; // If dependency field not found, consider condition met
    }

    // Get the current value from form values or submission data
    const dependencyValue = getFieldValueForDependency(
      targetField,
      dependencyField.field_id,
      formValues,
      allSections,
    );

    if (!dependencyValue) {
      return false; // If dependency field has no value, condition not met
    }

    // Check if any of the target options match the current value
    const checkValueMatch = (value) => {
      if (value === null || value === undefined) return false;

      // Handle object with value/label property
      const valueToCheck =
        typeof value === "object" ? value.value || value.label || value : value;

      return targetOptions.some((opt) => {
        const optValue =
          typeof opt === "object" ? opt.value || opt.label || opt : opt;
        return String(valueToCheck) === String(optValue);
      });
    };

    // Handle different value formats (string, object with value property, array)
    if (Array.isArray(dependencyValue)) {
      return dependencyValue.some(checkValueMatch);
    } else {
      return checkValueMatch(dependencyValue);
    }
  };

  // ALL field dependencies must be satisfied (AND logic)
  return fieldDependencies.every(checkFieldDependency);
};

